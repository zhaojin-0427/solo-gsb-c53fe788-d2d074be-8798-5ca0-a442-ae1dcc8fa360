#!/bin/sh
# 一键验收（docker compose --profile demo run --rm demo）：
# 1) 并发回滚竞态回归（进程内真实 ASGI + 真实 PostgreSQL 行锁，故障闸门注入交错）
# 2) 迁移缺片故障转移回归（模拟重启/内存池淘汰后的 failed 终态与安全重试）
# 3) 迁移会话创建并发幂等回归（同键对两条不同有效源记录的预查后交错）
# 4) 谱系逻辑销毁回归（销毁 × 迁移完成/分片领取/提交 的确定性先后、幂等回执）
# 5) 谱系限时恢复冻结回归（冻结 × 迁移完成/恢复创建/分片领取的确定性先后、
#    动态覆盖已有与未来迁移后代、重叠冻结、到期自动失效、提前解除、
#    CUSTODY_FROZEN 不消耗 nonce/不改计数/不触碰内存待累计分片、跨租户与已
#    销毁根拒绝、审计无秘密）
# 6) 完整端到端验收（正常恢复 + 各类拒绝依据 + 并发重放 + 跨策略迁移 +
#    谱系销毁 + 限时恢复冻结 + 审计哈希链重放）
set -e

echo "######################################################################"
echo "# 1/6 并发回滚竞态回归 (scripts.race_recovery)"
echo "######################################################################"
python -m scripts.race_recovery

echo
echo "######################################################################"
echo "# 2/6 迁移缺片故障转移回归 (scripts.race_migration)"
echo "######################################################################"
python -m scripts.race_migration

echo
echo "######################################################################"
echo "# 3/6 迁移创建并发幂等回归 (scripts.race_migration_start)"
echo "######################################################################"
python -m scripts.race_migration_start

echo
echo "######################################################################"
echo "# 4/6 谱系逻辑销毁回归 (scripts.race_destruction)"
echo "######################################################################"
python -m scripts.race_destruction

echo
echo "######################################################################"
echo "# 5/6 谱系限时恢复冻结回归 (scripts.race_freeze)"
echo "######################################################################"
python -m scripts.race_freeze

echo
echo "######################################################################"
echo "# 6/6 端到端验收 (scripts.demo)"
echo "######################################################################"
exec python -m scripts.demo
